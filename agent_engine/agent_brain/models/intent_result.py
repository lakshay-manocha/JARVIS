"""
===============================================================================
File Name   : intent_result.py
Module      : Agent Brain Models
Project     : JARVIS - Agent Decision Engine & Automation Engine

Description:
-------------
Represents the output generated by the Intent Detector.

This model stores the detected intent along with supporting metadata such as
confidence score and detection strategy. It acts as the standardized interface
between the Intent Detector and downstream reasoning modules.

Responsibilities:
    • Store detected intent
    • Store confidence score
    • Record detection strategy
    • Support future ML-based predictions
    • Provide a consistent structure across the pipeline

Author      : Team JARVIS
===============================================================================
"""

from pydantic import BaseModel, Field

from agent_engine.contracts.enums import IntentType


class IntentResult(BaseModel):
    """
    Represents the result of intent detection for a single task.
    """

    intent: IntentType = Field(
        ...,
        description="Detected intent."
    )

    confidence: float = Field(
        default=1.0,
        ge=0.0,
        le=1.0,
        description="Confidence score of the detected intent."
    )

    detection_method: str = Field(
        default="rule_based",
        description=(
            "Method used for intent detection "
            "(e.g. rule_based, ml_model)."
        )
    )

    reasoning: str | None = Field(
        default=None,
        description="Optional explanation of why the intent was detected."
    )