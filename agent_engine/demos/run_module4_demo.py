def print_actual_llm_input(llm_output: dict) -> None:
    """
    Displays the actual LLM-team output before it enters Module 4.

    No transformation is performed here.
    """

    print_banner("ACTUAL LLM TEAM OUTPUT")

    print_subtitle("Source")

    print(
        "sample_llm_outputs.py → SPRING_AI_CASE"
    )

    print_subtitle("Goal")

    print(llm_output["goal"])

    print_subtitle("Summary")

    print(llm_output["summary"])

    print_subtitle("Missing Information")

    if llm_output.get("missing_information"):

        for item in llm_output["missing_information"]:
            print(f"• {item}")

    else:

        print("None")

    print_subtitle("Tasks")

    for index, task in enumerate(
        llm_output["tasks"],
        start=1,
    ):
        print(
            f"{index}. {task}"
        )


