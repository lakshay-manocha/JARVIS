LINE = "═" * 90
SUB_LINE = "-" * 90


def print_banner(title: str) -> None:
    print("\n")
    print(LINE)
    print(title.center(90))
    print(LINE)


def print_subtitle(title: str) -> None:
    print(f"\n{title}")
    print(SUB_LINE)


# =============================================================================
# Demo Dispatcher
# =============================================================================


class Module4DemoDispatcher:
    """
    Demonstration implementation of the Module 4 ActionDispatcher contract.

    This dispatcher does NOT execute real automation.

    It only proves that the fully planned task reaches the execution
    boundary and that a normalized ExecutionOutcome is returned to the
    Agent Orchestrator.
    """

    def __init__(self) -> None:
        self.calls: list[tuple[int, int, str]] = []

    def dispatch(
        self,
        task,
        *,
        attempt: int,
        timeout_seconds: float | None = None,
    ) -> ExecutionOutcome:

        task_id = task.task_id
        action_text = task.original_text

        self.calls.append(
            (
                task_id,
                attempt,
                action_text,
            )
        )

        print(
            f"[DISPATCHER] Task {task_id} → execution interface reached"
        )

        print(
            f"             Action : {action_text}"
        )

        print(
            f"             Attempt: {attempt}"
        )

        return ExecutionOutcome(
            task_id=task_id,
            status=ExecutionStatus.COMPLETED,
            success=True,
            attempt=attempt,
            retry_count=max(attempt - 1, 0),
            max_retries=0,
        )


