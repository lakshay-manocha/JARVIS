# Event Listener
# =============================================================================


def event_listener(event: AgentEvent) -> None:
    """
    Displays orchestration events generated by the real EventBus.
    """

    if event.name == "request.started":

        print("[EVENT] request.started")
        print(
            f"        goal: {event.payload.get('goal')}"
        )

    elif event.name == "request.completed":

        print("[EVENT] request.completed")
        print(
            f"        task_count: "
            f"{event.payload.get('task_count')}"
        )

    elif event.name == "request.failed":

        print("[EVENT] request.failed")
        print(
            f"        error: "
            f"{event.payload.get('error')}"
        )

    elif event.name == "task.ready":

        print(
            f"[EVENT] task.ready | Task {event.task_id}"
        )

    elif event.name == "task.started":

        print(
            f"[EVENT] task.started | Task {event.task_id}"
        )

        print(
            f"        attempt: "
            f"{event.payload.get('attempt')}"
        )

    elif event.name == "task.decision":

        print(
            f"[EVENT] task.decision | Task {event.task_id}"
        )

        print(
            f"        action: "
            f"{event.payload.get('action')}"
        )

        print(
            f"        attempt: "
            f"{event.payload.get('attempt')}"
        )

        print(
            f"        reason: "
            f"{event.payload.get('reason')}"
        )

    elif event.name == "task.completed":

        print(
            f"[EVENT] task.completed | Task {event.task_id}"
        )

    elif event.name == "task.failed":

        print(
            f"[EVENT] task.failed | Task {event.task_id}"
        )

        print(
            f"        action: "
            f"{event.payload.get('action')}"
        )

        print(
            f"        reason: "
            f"{event.payload.get('reason')}"
        )


