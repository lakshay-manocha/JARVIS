def main() -> None:

    # -------------------------------------------------------------------------
    # Actual LLM-Team Output
    # -------------------------------------------------------------------------

    llm_output = SPRING_AI_CASE

    print_banner(
        "JARVIS MODULE 4 — FINAL LIVE DEMONSTRATION"
    )

    print(
        "This demonstration uses the actual LLM-team output."
    )

    print(
        "The output is passed unchanged into the real Module 4 Agent Brain."
    )

    print(
        "Module 5 automation is intentionally NOT executed."
    )

    print(
        "The Action Dispatcher shown here represents the existing "
        "Module 4 execution boundary."
    )

    # -------------------------------------------------------------------------
    # Display actual input
    # -------------------------------------------------------------------------

    print_actual_llm_input(llm_output)

    # -------------------------------------------------------------------------
    # Build real Module 4 components
    # -------------------------------------------------------------------------

    dispatcher = Module4DemoDispatcher()

    event_bus = EventBus()

    event_bus.subscribe(
        "*",
        event_listener,
    )

    orchestrator_instance = AgentOrchestrator(
        dispatcher,
        event_bus=event_bus,
    )

    # Make the result printer able to inspect the actual StateManager.
    global orchestrator
    orchestrator = orchestrator_instance

    # -------------------------------------------------------------------------
    # Convert actual LLM output into the canonical LLMPlan
    # -------------------------------------------------------------------------

    print_banner(
        "MODULE 4 : AGENT BRAIN PROCESSING"
    )

    print(
        "Passing actual LLM-team output to AgentOrchestrator..."
    )

    print(
        "The real Module 4 pipeline will now execute:"
    )

    print(
        "LLMPlan → Validation → Interpretation → "
        "Graph → Planning → Orchestration"
    )

    print()

    plan = LLMPlan(
        **llm_output
    )

    # -------------------------------------------------------------------------
    # Execute the REAL Agent Orchestrator
    # -------------------------------------------------------------------------

    result = orchestrator_instance.run(plan)

    # -------------------------------------------------------------------------
    # Display result
    # -------------------------------------------------------------------------

    print_module4_result(
        result,
        dispatcher,
    )

    # -------------------------------------------------------------------------
    # Final status
    # -------------------------------------------------------------------------

    print("\n" + LINE)

    if result.status == ResultStatus.SUCCESS:

        print(
            "MODULE 4 AGENT BRAIN LIVE DEMONSTRATION "
            "COMPLETED SUCCESSFULLY"
        )

    else:

        print(
            "MODULE 4 AGENT BRAIN LIVE DEMONSTRATION "
            "COMPLETED WITH FAILURE"
        )

    print(LINE)


# =============================================================================
# Entry Point
# =============================================================================


if __name__ == "__main__":
    main()